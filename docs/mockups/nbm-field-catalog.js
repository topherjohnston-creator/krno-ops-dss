export function getNbmFieldById(id) {
  return NBM_FIELD_CATALOG.find(field => field.id === id);
}

export function recommendedNbmFieldsForHazard(hazardId) {
  return NBM_FIELD_CATALOG.filter(field => field.recommendedForHazards.includes(hazardId));
}

export function fieldLabel(field) {
  if (!field) return "Select NBM field";
  const product = field.qmdAvailable ? "QMD" : "Core";
  return `${product} - ${field.weatherType} - ${field.fieldName}`;
}
